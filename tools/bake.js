/* Emberfall - bake step.
 *
 * This is the step that used to be done by hand, which is why the browser kept
 * serving stale code. It does four things, all deterministic:
 *
 *   1. computes a content hash over the data files and the client sources
 *   2. stamps it into data/world.json as "build"
 *   3. regenerates js/gamedata.js (the embedded world the browser client reads,
 *      because shared hosts 403 the /data/ directory)
 *   4. rewrites every ?v=... in index.html to the new hash
 *   5. copies the data files into godot/data/ so the Godot client and the
 *      in-editor map editor read exactly the same world as the server
 *
 * Run it after apply_towns.js and apply_resources.js, before validate_world.js:
 *
 *     node tools/apply_towns.js
 *     node tools/apply_resources.js
 *     node tools/bake.js
 *     node tools/validate_world.js
 *
 * The hash covers the client sources as well as the data, because a code change
 * with unchanged data still has to bust the cache.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.join(__dirname, '..');
const DATA = path.join(ROOT, 'data');
const GODOT_DATA = path.join(ROOT, 'godot', 'data');

/* The JSON the game loads. Order is fixed so the hash is stable. */
const DATA_FILES = ['items.json', 'npcs.json', 'quests.json', 'magic.json', 'world.json'];

/* Client sources, sorted, so adding a file does not reorder the hash input. */
function clientSources() {
  const out = [];
  const jsDir = path.join(ROOT, 'js');
  if (fs.existsSync(jsDir)) {
    fs.readdirSync(jsDir).sort().forEach(function (f) {
      /* gamedata.js is generated from the data files, so including it would
         make the hash depend on itself. */
      if (f === 'gamedata.js') return;
      if (f.endsWith('.js')) out.push(path.join('js', f));
    });
  }
  const cssFile = path.join('css', 'style.css');
  if (fs.existsSync(path.join(ROOT, cssFile))) out.push(cssFile);
  return out;
}

/* ---- 1. load the data ------------------------------------------------ */
const loaded = {};
DATA_FILES.forEach(function (f) {
  const p = path.join(DATA, f);
  if (!fs.existsSync(p)) {
    console.error('missing data/' + f + ' - run node tools/apply_towns.js first');
    process.exit(1);
  }
  loaded[f] = JSON.parse(fs.readFileSync(p, 'utf8'));
});

/* ---- 2. compute the hash -------------------------------------------- */
const h = crypto.createHash('sha256');

/* World content without the old stamp, so re-baking an unchanged world gives
   the same hash instead of chasing its own tail. */
const worldForHash = Object.assign({}, loaded['world.json']);
delete worldForHash.build;

DATA_FILES.forEach(function (f) {
  h.update(f + '\0');
  h.update(f === 'world.json' ? JSON.stringify(worldForHash) : JSON.stringify(loaded[f]));
  h.update('\0');
});
const sources = clientSources();
sources.forEach(function (rel) {
  h.update(rel + '\0');
  h.update(fs.readFileSync(path.join(ROOT, rel)));
  h.update('\0');
});

const BUILD = h.digest('hex').slice(0, 12);

/* ---- 3. stamp world.json -------------------------------------------- */
const world = loaded['world.json'];
const prev = world.build || '(none)';
world.build = BUILD;
fs.writeFileSync(path.join(DATA, 'world.json'), JSON.stringify(world));

/* ---- 4. regenerate js/gamedata.js ----------------------------------- */
/* Keys in the order the client expects. */
const bundle = {
  items: loaded['items.json'],
  npcs: loaded['npcs.json'].npcs,
  shops: loaded['npcs.json'].shops,
  quests: loaded['quests.json'],
  spells: loaded['magic.json'].spells,
  prayers: loaded['magic.json'].prayers,
  world: world
};
const gamedata =
  '/* generated by tools/bake.js - do not edit. build ' + BUILD + ' */\n'
  + 'window.RFDATA = ' + JSON.stringify(bundle) + ';\n';
fs.writeFileSync(path.join(ROOT, 'js', 'gamedata.js'), gamedata);

/* ---- 5. rewrite ?v=... in index.html -------------------------------- */
let rewrote = 0;
const idx = path.join(ROOT, 'index.html');
if (fs.existsSync(idx)) {
  const before = fs.readFileSync(idx, 'utf8');
  const after = before.replace(/(\?v=)[0-9a-f]{6,64}/g, function () {
    rewrote++;
    return '?v=' + BUILD;
  });
  if (after !== before) fs.writeFileSync(idx, after);
}

/* ---- 6. mirror the data into the Godot project ---------------------- */
/* The Godot client reads these from res://data/. Keeping them as real files
   rather than regenerating them in GDScript means there is one world
   definition, not two that can drift apart. */
let copied = 0;
if (fs.existsSync(path.join(ROOT, 'godot'))) {
  fs.mkdirSync(GODOT_DATA, { recursive: true });
  DATA_FILES.concat(['authored_world.json']).forEach(function (f) {
    const src = path.join(DATA, f);
    if (!fs.existsSync(src)) return;
    fs.copyFileSync(src, path.join(GODOT_DATA, f));
    copied++;
  });
  /* A tiny file the Godot client reads to know which build it was exported
     against, so a stale .pck is as visible as a stale script was. */
  fs.writeFileSync(path.join(GODOT_DATA, 'build.txt'), BUILD + '\n');
}

console.log('bake: build ' + prev + ' -> ' + BUILD);
console.log('  hashed      ' + DATA_FILES.length + ' data files + ' + sources.length + ' client sources');
console.log('  gamedata.js ' + (fs.statSync(path.join(ROOT, 'js', 'gamedata.js')).size / 1024).toFixed(1) + ' KB');
console.log('  index.html  ' + rewrote + ' cache-busted urls');
console.log('  godot/data  ' + copied + ' files mirrored');
